"""Writes src/test_packets.inc: two GT7 packets encrypted by an independent implementation
(pycryptodome), so the self-test checks the tool's own Salsa20 and field offsets against
something it did not produce itself.

    python3 tools/gen_test_packets.py
"""
import struct
from pathlib import Path

from Crypto.Cipher import Salsa20

KEY = b"Simulator Interface Packet GT7 ver 0.0"[:32]
MAGIC = 0x47375330


def packet(size: int, xor: int, seed: int, packet_id: int, flags: int, speed: float, steering: float) -> bytes:
    plain = bytearray((i * 37 + 11) & 0xFF for i in range(size))   # filler that is not all zero
    struct.pack_into("<I", plain, 0x00, MAGIC)
    struct.pack_into("<f", plain, 0x4C, speed)
    struct.pack_into("<i", plain, 0x70, packet_id)
    struct.pack_into("<H", plain, 0x8E, flags)
    if size >= 316:
        struct.pack_into("<f", plain, 0x128, steering)
    nonce = struct.pack("<II", seed ^ xor, seed)
    out = bytearray(Salsa20.new(key=KEY, nonce=nonce).encrypt(bytes(plain)))
    struct.pack_into("<I", out, 0x40, seed)                       # the game sends the seed in the clear
    return bytes(out)


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


text = "// Generated by tools/gen_test_packets.py - do not edit.\n"
text += "// B: id 123456, flags 0x0199, 41.5 m/s, steering -0.75 rad.  A: id 777, flags 0x0003, 12.25 m/s.\n"
text += c_array("kTestPacketB", packet(316, 0xDEADBEEF, 0x1A2B3C4D, 123456, 0x0199, 41.5, -0.75))
text += c_array("kTestPacketA", packet(296, 0xDEADBEAF, 0x0BADF00D, 777, 0x0003, 12.25, 0.0))
Path(__file__).resolve().parents[1].joinpath("src", "test_packets.inc").write_text(text)
print("wrote src/test_packets.inc")
